// components/index.d.ts: documentation of each component's props, which the
// design system reads as `<Comp>Props`. Written from the mirror's own type
// declarations (and the SUI types they name), so the docs are the types.
import ts from "typescript";

export interface TypeDecl {
  readonly name: string;
  readonly text: string;
}

/** The exported interfaces and type aliases of a TypeScript source, as written. */
export const exportedTypes = (source: string): readonly TypeDecl[] => {
  const file = ts.createSourceFile(
    "x.ts",
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  return file.statements.flatMap((s) =>
    (ts.isInterfaceDeclaration(s) || ts.isTypeAliasDeclaration(s)) &&
    s.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
      ? [{ name: s.name.text, text: s.getText(file) }]
      : [],
  );
};

const words = (text: string): ReadonlySet<string> =>
  new Set(text.match(/[A-Za-z_]\w*/g) ?? []);

/** The declarations `roots` name, and those they name in turn, in source order; first of a name wins. */
export const reachable = (
  decls: readonly TypeDecl[],
  roots: readonly string[],
): readonly TypeDecl[] => {
  const byName = new Map<string, TypeDecl>();
  for (const d of decls) if (!byName.has(d.name)) byName.set(d.name, d);
  const seen = new Set<string>();
  const visit = (name: string): void => {
    const decl = byName.get(name);
    if (!decl || seen.has(name)) return;
    seen.add(name);
    for (const word of words(decl.text)) visit(word);
  };
  for (const root of roots) visit(root);
  return [...byName.values()].filter((d) => seen.has(d.name));
};

export interface ComponentDecl {
  readonly name: string;
  /** The props type it takes. */
  readonly props: string;
}

/** index.d.ts: the reachable types, then a `<Comp>Props` and a declaration per component. */
export const indexDeclarations = (
  decls: readonly TypeDecl[],
  components: readonly ComponentDecl[],
): string => {
  const types = reachable(
    decls,
    components.map((c) => c.props),
  );
  const own = new Set(decls.map((d) => d.name));
  return [
    "// SUI for React (window.Sui). Generated by react-mirror/build from the mirror's types.",
    'import type { CSSProperties, HTMLAttributes, ReactElement, ReactNode } from "react";',
    "",
    ...types.map(
      (d) => `${d.text.startsWith("export") ? "" : "export "}${d.text}\n`,
    ),
    ...components.flatMap((c) => {
      const alias = `${c.name}Props`;
      return [
        ...(alias === c.props || own.has(alias)
          ? []
          : [`export type ${alias} = ${c.props};`]),
        `export declare const ${c.name}: (props: ${alias}) => ReactElement;`,
      ];
    }),
    "",
  ].join("\n");
};
